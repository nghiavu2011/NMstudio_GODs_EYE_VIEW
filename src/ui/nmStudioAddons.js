export function initNmStudioAddons() {
  // Load saved language
  const savedLang = localStorage.getItem('nm_studio_lang');
  if (savedLang === 'en' || savedLang === 'vi') {
    currentLang = savedLang;
  } else {
    currentLang = 'vi';
  }

  injectModals();

  // Attach button triggers
  const helpBtn = document.getElementById('nm-help-btn');
  if (helpBtn) {
    helpBtn.addEventListener('click', (e) => {
      e.preventDefault();
      openHelpModal();
    });
  }

  const coffeeBtn = document.getElementById('nm-coffee-btn');
  if (coffeeBtn) {
    coffeeBtn.addEventListener('click', (e) => {
      e.preventDefault();
      openCoffeeModal();
    });
  }

  // Language slice toggle
  document.querySelectorAll('.nm-slice-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      if (lang) setLanguage(lang);
    });
  });

  applyTranslations();
  updateSliceButtons();

  // Retry after layer catalog finishes bootstrapping
  setTimeout(applyTranslations, 600);
  setTimeout(applyTranslations, 1800);
}
